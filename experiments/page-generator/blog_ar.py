def ar_date(d):
    # "July 2, 2026" -> "2 يوليو 2026"
    month, rest = d.split(" ", 1)
    day, year = rest.replace(",", "").split()
    return "%s %s %s" % (day, AR_MONTHS[month], year)

def ar_minutes(n):
    # Arabic counted-noun agreement for reading time
    if n == 1:
        return "قراءة دقيقة"
    if n == 2:
        return "قراءة دقيقتين"
    if 3 <= n <= 10:
        return "قراءة %d دقائق" % n
    return "قراءة %d دقيقة" % n
